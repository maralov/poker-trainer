function Guide({ title, rows }: { title: string; rows: readonly [string, string][] }) {
  return (
    <>
      <h4>{title}</h4>
      <table>
        <tbody>
          {rows.map(([name, text]) => (
            <tr key={name}>
              <td>{name}</td>
              <td className="m">{text}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </>
  )
}

